// Static reply templates for the WhatsApp intake bot — one canonical English template per
// key, translated once (by hand, not per-message) into every language the bot may reply in.
// Runtime cost is a plain object lookup + {token} interpolation: no network call, no
// per-message translation risk. All computed values (case-strength %, checklist ticks,
// literal citizen-provided values) are interpolated as-is — only the surrounding prose is
// ever per-language text, so a bad translation can never corrupt a number.
//
// Legal/regulatory citations (RBI circular year, IT Rules year, day counts) are kept as
// literal tokens in every language's timeline_* strings — translate the sentence around them,
// never the figures themselves.
//
// Launch scope: English, Hindi, Hinglish (romanized Hindi), Bengali, Tamil, Telugu, Marathi,
// Gujarati, Kannada, Malayalam, Punjabi, Urdu, Odia. Any other detected language falls back to
// English (see resolveLanguage) — add more LangKey entries + a TEMPLATES block to extend.

export type LangKey =
  | "en" | "hi" | "hi-Latn" | "bn" | "gu" | "kn" | "ml" | "mr" | "or" | "pa" | "ta" | "te" | "ur";

export const DEFAULT_LANG: LangKey = "en";

// Ordered so more specific matches (Hinglish) are checked before their broader parent (Hindi).
const LANG_MATCHERS: Array<[RegExp, LangKey]> = [
  [/hinglish|hindi.*latin|latin.*hindi/i, "hi-Latn"],
  [/hindi/i, "hi"],
  [/bengali|bangla/i, "bn"],
  [/gujarati/i, "gu"],
  [/kannada/i, "kn"],
  [/malayalam/i, "ml"],
  [/marathi/i, "mr"],
  [/odia|oriya/i, "or"],
  [/punjabi/i, "pa"],
  [/tamil/i, "ta"],
  [/telugu/i, "te"],
  [/urdu/i, "ur"],
  [/english/i, "en"],
];

// Maps Gemini's free-text `language` field (e.g. "Hindi (Devanagari)", "Kannada") onto a
// canonical template key. Unrecognized/empty input falls back to English rather than guessing.
export function resolveLanguage(detected: string | null | undefined): LangKey {
  const s = (detected || "").trim();
  if (!s) return DEFAULT_LANG;
  // A caller can pass either Gemini's verbose free-text guess ("Hindi (Devanagari)") or an
  // already-canonical LangKey code round-tripped back from a prior turn ("hi"). The regexes
  // below only match the former -- a short code like "hi" contains none of them ("hindi" can't
  // appear inside a 2-character string) and fell through to DEFAULT_LANG every time, silently
  // resetting the conversation to English on any turn that re-resolved a previously-locked
  // language. Recognize an already-canonical code first so the round trip is lossless.
  if (isLangKey(s)) return s;
  for (const [re, key] of LANG_MATCHERS) if (re.test(s)) return key;
  return DEFAULT_LANG;
}

export function isLangKey(value: unknown): value is LangKey {
  return typeof value === "string" && LANG_MATCHERS.some(([, key]) => key === value) || value === "en";
}

type TemplateSet = Record<string, string>;

// Interpolates {token} placeholders. Falls back to the English string (then the bare key) if a
// language is missing a key — the table below is filled for every key in every language, but
// this keeps a future partial addition from ever rendering a blank reply.
export function t(key: string, lang: LangKey, vars?: Record<string, string>): string {
  const raw = TEMPLATES[lang]?.[key] ?? TEMPLATES.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? "");
}

